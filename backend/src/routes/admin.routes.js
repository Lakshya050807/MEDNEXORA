import express, { Router } from 'express';
import { createCatalogController } from '../controllers/catalog.controller.js';
import { createAdminController } from '../controllers/admin.controller.js';
import { createAdminAuthController } from '../controllers/admin-auth.controller.js';
import { requireAdminAuth } from '../middleware/requireAdminAuth.js';
import { verifyOrigin } from '../middleware/verifyOrigin.js';
import { createRateLimiter } from '../middleware/rateLimit.js';
import { createAdminUploadController } from '../controllers/admin-upload.controller.js';

export function createAdminRoutes({ UserModel, OrderModel, RefundModel, privateStorageDir, PurchasedAccessModel, CourseProgressModel, ...catalogModels }) {
  const router = Router();
  const controller = createCatalogController({ ...catalogModels, OrderModel, PurchasedAccessModel });
  const adminController = createAdminController({ UserModel, OrderModel, RefundModel, PurchasedAccessModel, CourseProgressModel, ...catalogModels });
  const adminAuth = createAdminAuthController({ UserModel });
  const uploads = createAdminUploadController({ privateStorageDir });
  router.use(createRateLimiter({ windowMs: 60 * 1000, max: 300 }));
  const adminLoginLimiter = createRateLimiter({ windowMs: 15 * 60 * 1000, max: 5 });
  router.post('/login', verifyOrigin, adminLoginLimiter, adminAuth.login);
  router.post('/logout', verifyOrigin, adminAuth.logout);
  router.use(requireAdminAuth({ UserModel }));
  router.post('/uploads/pdf', verifyOrigin, createRateLimiter({ windowMs: 60 * 1000, max: 10 }), express.raw({ type: 'application/pdf', limit: '50mb' }), uploads.uploadPdf);
  router.get('/me', adminAuth.profile);
  router.post('/password', verifyOrigin, createRateLimiter({ windowMs: 15 * 60 * 1000, max: 5 }), adminAuth.changePassword);
  router.get('/overview', adminController.overview);
  router.get('/products', adminController.products);
  router.get('/exams', adminController.exams);
  router.get('/subjects', adminController.subjects);
  router.get('/chapters', adminController.chapters);
  router.get('/topics', adminController.topics);
  router.get('/courses', adminController.courses);
  router.get('/question-banks', adminController.questionBanks);
  router.get('/mock-tests', adminController.mockTests);
  router.get('/orders', adminController.orders);
  router.post('/orders/:orderId/refund-review', verifyOrigin, adminController.reviewPartialRefund);
  router.get('/students', adminController.students);
  router.post('/exams', verifyOrigin, controller.admin.createExam);
  router.patch('/exams/:id', verifyOrigin, controller.admin.updateExam);
  router.post('/subjects', verifyOrigin, controller.admin.createSubject);
  router.patch('/subjects/:id', verifyOrigin, controller.admin.updateSubject);
  router.delete('/subjects/:id', verifyOrigin, controller.admin.deleteSubject);
  router.post('/chapters', verifyOrigin, controller.admin.createChapter);
  router.patch('/chapters/:id', verifyOrigin, controller.admin.updateChapter);
  router.delete('/chapters/:id', verifyOrigin, controller.admin.deleteChapter);
  router.post('/topics', verifyOrigin, controller.admin.createTopic);
  router.patch('/topics/:id', verifyOrigin, controller.admin.updateTopic);
  router.delete('/topics/:id', verifyOrigin, controller.admin.deleteTopic);
  router.post('/products', verifyOrigin, controller.admin.createProduct);
  router.patch('/products/:id', verifyOrigin, controller.admin.updateProduct);
  router.delete('/products/:id', verifyOrigin, controller.admin.deleteProduct);
  router.post('/courses', verifyOrigin, controller.admin.createCourse);
  router.patch('/courses/:id', verifyOrigin, controller.admin.updateCourse);
  router.post('/question-banks', verifyOrigin, controller.admin.createQuestionBank);
  router.patch('/question-banks/:id', verifyOrigin, controller.admin.updateQuestionBank);
  router.post('/mock-tests', verifyOrigin, controller.admin.createMockTest);
  router.patch('/mock-tests/:id', verifyOrigin, controller.admin.updateMockTest);
  return router;
}

export default createAdminRoutes;
